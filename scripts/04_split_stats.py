"""Write results/tables/split_stats.md: speakers / utterances / hours per split,
speaker-disjointness assertion, and test sentences that also occur in train.
Also checks whether VoxPopuli's own validation/test labels were speaker-disjoint."""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.config import CLEANED, RAW, SPLITS, TABLES  # noqa: E402
from src.normalize import normalize  # noqa: E402


def load(split):
    return pd.read_csv(SPLITS / f"{split}.tsv", sep="\t", keep_default_na=False, quoting=3,
                       dtype={"speaker": str})


def main():
    parts = {s: load(s) for s in ("train", "dev", "test")}
    spk = {s: set(p.speaker) for s, p in parts.items()}
    for a, b in (("train", "dev"), ("train", "test"), ("dev", "test")):
        assert not (spk[a] & spk[b]), f"speaker overlap {a}/{b}: {spk[a] & spk[b]}"

    lines = ["# Split statistics", "",
             "Generated by `scripts/04_split_stats.py`. Speakers are pairwise disjoint (asserted).", "",
             "| Split | Speakers | Utterances | Hours | Female hours share |",
             "|---|---|---|---|---|"]
    for s, p in parts.items():
        d = p.duration.astype(float)
        fem = d[p.gender == "female"].sum() / d.sum()
        lines.append(f"| {s} | {p.speaker.nunique()} | {len(p)} | {d.sum() / 3600:.2f} | {fem:.1%} |")
    tot = pd.concat(parts.values())
    lines.append(f"| **total** | {tot.speaker.nunique()} | {len(tot)} | "
                 f"{tot.duration.astype(float).sum() / 3600:.2f} | |")

    train_sents = set(parts["train"].text.map(normalize))
    for s in ("dev", "test"):
        n = parts[s].text.map(normalize).isin(train_sents).sum()
        lines += ["", f"**{s} sentences found word-for-word in train (after normalization):** "
                      f"{n} of {len(parts[s])} ({n / len(parts[s]):.2%})"]

    raw = pd.read_csv(RAW / "metadata.tsv", sep="\t", keep_default_na=False, quoting=3,
                      dtype={"speaker_id": str})
    v = set(raw[raw.source_split == "validation"].speaker_id)
    t = set(raw[raw.source_split == "test"].speaker_id)
    lines += ["", "**VoxPopuli's own split (checked, not used):** "
                  f"validation has {len(v)} speakers, test has {len(t)}, and {len(v & t)} speakers "
                  "appear in both, so the official split is not speaker-disjoint. We re-split."]
    cleaned = pd.read_csv(CLEANED / "metadata.tsv", sep="\t", keep_default_na=False, quoting=3)
    assert len(cleaned) == len(tot) and set(cleaned.utt_id) == set(tot.utt_id)
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / "split_stats.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
